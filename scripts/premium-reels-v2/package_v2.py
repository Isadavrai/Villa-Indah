from pathlib import Path
import hashlib, json, shutil, zipfile

out=Path('dist/reels-v2');kit=Path('work/v2-kit');kit.mkdir(parents=True,exist_ok=True)
for name in ('build_v2.py','verify_v2.py'):
 shutil.copy2(Path('scripts/premium-reels-v2')/name,kit/name)
for p in out.iterdir():
 if p.is_file() and p.suffix.lower()!='.mp4':shutil.copy2(p,kit/p.name)
score=Path('work/premium_v2/render/original_premium_score.wav')
if score.exists():shutil.copy2(score,kit/'Original_Premium_Score.wav')
(kit/'requirements.txt').write_text('numpy\nPillow\nopencv-python-headless\nscipy\n')
(kit/'README.txt').write_text('''Villa Indah Premium V2 — RU + EN

Reference-led edit: full-screen imagery, 1.5-second beat-synced scenes,
centered static typography, selective directional transitions.
No copy about loungers or shared areas appears in either video.

Rebuild:
  python -m pip install -r requirements.txt
  python build_v2.py --repo Villa-Indah --out dist/reels-v2
  python verify_v2.py --repo Villa-Indah --out dist/reels-v2

Requires FFmpeg. Music is an original synthesized score generated by build_v2.py;
no third-party recordings or samples are used.
''')
checks='\n'.join(hashlib.sha256(p.read_bytes()).hexdigest()+'  '+p.name for p in sorted(out.glob('*.mp4')))+'\n';(out/'SHA256SUMS.txt').write_text(checks);shutil.copy2(out/'SHA256SUMS.txt',kit)
report=json.loads((out/'technical_verification_v2.json').read_text())
lines=['VILLA INDAH PREMIUM V2 — ПРОВЕРКА','']
for lang,r in report.items():lines.extend([f'{lang}: {r["duration_seconds"]} с, {r["decoded_frames"]} кадров, {r["resolution"][0]}×{r["resolution"][1]}, {r["fps"]}',f'H.264/AAC, {r["pixel_format"]}, Rec.709, faststart',f'Ошибки декодирования: {r["decode_errors"] or "нет"}',f'Проверок титров: {r["caption_checks"]}; смещение: {r["caption_max_displacement_px"]} px',''])
lines.extend(['Фразы о лежаках и общих зонах отсутствуют.','Титры отцентрированы и накладываются после движения изображения.'])
(out/'Technical_Report_V2_RU.txt').write_text('\n'.join(lines));shutil.copy2(out/'Technical_Report_V2_RU.txt',kit)
with zipfile.ZipFile(out/'Villa_Indah_Premium_V2_Production_Kit.zip','w',zipfile.ZIP_DEFLATED) as z:
 for p in sorted(kit.rglob('*')):
  if p.is_file():z.write(p,p.relative_to(kit))
with zipfile.ZipFile(out/'Villa_Indah_Premium_V2_Production_Kit.zip') as z:assert z.testzip() is None
